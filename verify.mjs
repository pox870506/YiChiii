import assert from 'node:assert/strict';
import fs from 'node:fs';
import {initialDraft,validateDraft,markdown,migrateDraft,travelers,flights} from './lib/trip.ts';
import {foodLists} from './lib/foods.ts';
import {climate,weatherNotes} from './lib/weather.ts';
import {estimateBudget,lodgingQuotes} from './lib/budget.ts';
const d=structuredClone(initialDraft);d.notes['2026-11-19']='保留備註';
