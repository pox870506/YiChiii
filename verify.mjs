const old={...d,planRevision:3};assert.equal(migrateDraft(old).notes['2026-11-19'],'保留備註');
const p=fs.readFileSync('app/page.tsx','utf8');assert.equal(p.slice(p.indexOf(' const day=' )).trim(),fs.readFileSync('mobile-view.part','utf8').trim());
assert(!p.includes('value="sources"'));assert(!fs.readFileSync('app/budget.tsx','utf8').includes('travel-budget.txt'));
fs.writeFileSync('exports/德荷旅遊.md',markdown(initialDraft));
fs.writeFileSync('exports/德荷旅遊.json',JSON.stringify({...initialDraft,reference:{travelers,flights,foodLists,climate,weatherNotes,lodgingQuotes,budget:estimateBudget()}},null,2));
