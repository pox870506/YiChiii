assert.equal(d.days.length,14);assert.equal(d.days.filter(x=>x.stay).length,10);
assert.equal(travelers.length,5);assert.equal(estimateBudget().lodging,100098/5);
assert(d.stays[2].name.includes('Cityden'));assert.equal(lodgingQuotes[2].totalTwd,43000);
